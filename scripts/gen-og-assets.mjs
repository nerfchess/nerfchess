// Regenerates the embedded assets of the next/og link previews:
//
// src/lib/og/fontData.ts: Noto Sans 400 and 700 (the site's face,
// docs/design-system.md section 3) subset to the characters a link preview can
// contain, embedded as base64 so the next/og renderer has them on every
// runtime (next dev, next build, and the Cloudflare worker, which has no file
// system to read a .ttf from at request time).
//
// src/lib/og/pieces.ts: the cburnett piece set (the site default, served from
// public/piece/lichess/cburnett) as data URIs, for the board in game previews.
//
// src/lib/og/logo.ts: the logo mark (public/icon-192.png) as base64.
//
//   node scripts/gen-og-assets.mjs
//
// The subset is printable ASCII, Latin-1, Latin Extended-A (every accented
// Latin letter a club or tournament name is likely to use) and the handful of
// punctuation marks the copy uses. Satori needs TTF, OTF or WOFF (not WOFF2);
// Google Fonts serves TTF to a user agent it does not recognise.
//
// Noto Sans: Copyright 2022 The Noto Project Authors, SIL Open Font License 1.1.

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const OUT = path.join(ROOT, "src", "lib", "og", "fontData.ts");

const ranges = [
  [0x20, 0x7e],
  [0xa0, 0xff],
  [0x100, 0x17f],
];
const extra = [0x2013, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x2032, 0x2033, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x2264, 0x2265];
const chars = ranges.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => a + i)).concat(extra);
const text = String.fromCodePoint(...chars);

async function ttf(weight) {
  const css = await fetch(
    `https://fonts.googleapis.com/css2?family=Noto+Sans:wght@${weight}&text=${encodeURIComponent(text)}`,
    { headers: { "user-agent": "Mozilla/4.0" } },
  ).then((r) => r.text());
  const url = /url\((https:[^)]+)\)\s*format\('truetype'\)/.exec(css)?.[1];
  if (!url) throw new Error(`no truetype url for weight ${weight}:\n${css}`);
  const buf = Buffer.from(await fetch(url).then((r) => r.arrayBuffer()));
  if (buf.readUInt32BE(0) !== 0x00010000) throw new Error(`weight ${weight} is not a TrueType file`);
  return buf;
}

const regular = await ttf(400);
const bold = await ttf(700);
const chunk = (b64) => b64.match(/.{1,120}/g).map((l) => `  "${l}"`).join(" +\n");
const src = `// GENERATED by scripts/gen-og-assets.mjs. Do not edit by hand.
//
// Noto Sans 400 and 700, subset to printable ASCII, Latin-1, Latin Extended-A
// and a few punctuation marks (${chars.length} code points), for the next/og link
// previews. Noto Sans: Copyright 2022 The Noto Project Authors, licensed under
// the SIL Open Font License 1.1 (https://openfontlicense.org).

/** The code points both subsets cover; anything else is dropped from preview
 *  text before rendering (see ogText in ./text.ts). */
export const OG_FONT_RANGES: [number, number][] = ${JSON.stringify(ranges)};
export const OG_FONT_EXTRA: number[] = ${JSON.stringify(extra)};

export const NOTO_SANS_400_B64 =
${chunk(regular.toString("base64"))};

export const NOTO_SANS_700_B64 =
${chunk(bold.toString("base64"))};
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, src);
console.log(`wrote ${path.relative(ROOT, OUT)}: 400 ${regular.length} bytes, 700 ${bold.length} bytes`);

const PIECE_DIR = path.join(ROOT, "public", "piece", "lichess", "cburnett");
const pieceLines = [];
for (const color of ["w", "b"]) {
  for (const kind of ["K", "Q", "R", "B", "N", "P"]) {
    const svg = fs.readFileSync(path.join(PIECE_DIR, `${color}${kind}.svg`));
    pieceLines.push(`  ${color}${kind}: "data:image/svg+xml;base64,${svg.toString("base64")}",`);
  }
}
const PIECES_OUT = path.join(ROOT, "src", "lib", "og", "pieces.ts");
fs.writeFileSync(
  PIECES_OUT,
  `// GENERATED by scripts/gen-og-assets.mjs. Do not edit by hand.
//
// The cburnett pieces (public/piece/lichess/cburnett, the site default set)
// as data URIs, so a next/og preview can draw a real board without fetching.
// cburnett: Colin M.L. Burnett, GPLv2+ / GFDL / BSD, via lichess.

export const OG_PIECES: Record<string, string> = {
${pieceLines.join("\n")}
};
`,
);
console.log(`wrote ${path.relative(ROOT, PIECES_OUT)}`);

// The logo mark with its transparent background (public/icon-192.png), drawn
// at 96px or less in a preview, so the 192px raster is sharp at 2x.
const LOGO_OUT = path.join(ROOT, "src", "lib", "og", "logo.ts");
const logo = fs.readFileSync(path.join(ROOT, "public", "icon-192.png"));
fs.writeFileSync(
  LOGO_OUT,
  `// GENERATED by scripts/gen-og-assets.mjs from public/icon-192.png. Do not edit by hand.

export const OG_LOGO_PNG =
${chunk(logo.toString("base64"))};
`,
);
console.log(`wrote ${path.relative(ROOT, LOGO_OUT)}`);
