// Generates migrations/0014_seed_leaderboard.sql: ~150 fake players seeded onto
// the Nerf and Buff leaderboards. Deterministic (fixed PRNG seed) so re-running
// produces the same file. Fake users:
//   - id = 'seed_' || username_lower  (unique, recognizable prefix)
//   - password_hash = 'unusable'      (can never log in; cleanly removable)
// Only base users columns (migration 0001) are written, since avatar/is_guest/
// banned_until are added at runtime by ensureSchema. Rows use INSERT OR IGNORE
// so the migration is safe to re-run. A revert lives in
// scripts/revert-seed-leaderboard.sql.
//
//   node scripts/gen-seed-leaderboard.cjs > migrations/0014_seed_leaderboard.sql

// Deterministic PRNG (mulberry32).
function mulberry32(a) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(0x0ec0ffee);
const pick = (arr) => arr[Math.floor(rand() * arr.length)];
const between = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));

// Lichess-flavored handle parts. Generic chess mood, no real player names.
const ADJ = [
  "Blunder", "Zugzwang", "EnPassant", "Fianchetto", "Zwischenzug", "Endgame",
  "Gambit", "Prophylaxis", "Tempo", "Passed", "Doubled", "Isolated", "Fortress",
  "Skewered", "Pinned", "Forked", "Smothered", "Stalemate", "Perpetual", "Sac",
  "Windmill", "Underpromote", "Overprotect", "Desperado", "Zeitnot", "Flagged",
  "Berserk", "Bullet", "Hyperbullet", "Rapid", "Classical", "Correspondence",
  "Caro", "Sicilian", "Najdorf", "Petrov", "Benoni", "Slav", "Grunfeld", "Pirc",
  "Scandi", "Dragon", "Hedgehog", "London", "Stonewall", "Colle", "Vienna",
];
const NOUN = [
  "Knight", "Bishop", "Rook", "Pawn", "Queen", "King", "Castle", "Check",
  "Mate", "Fork", "Pin", "Skewer", "Outpost", "Battery", "Phalanx", "Wing",
  "Flank", "Center", "Diagonal", "File", "Rank", "Square", "Tempo", "Zwerg",
  "Patzer", "Woodpusher", "Fish", "Shark", "Falcon", "Hippo", "Octopus",
  "Monarch", "Regent", "Vizier", "Jester", "Warden", "Sentinel", "Marshal",
  "Gambiteer", "Tactician", "Grinder", "Swindler", "Prodigy", "Novice",
];
const SUFFIX = [
  "", "", "", "64", "88", "99", "1600", "1200", "2000", "_", "xd", "TV",
  "OTB", "IRL", "GG", "420", "007", "42", "9000", "Prime", "Zero", "Jr",
];

function makeName(used) {
  for (let tries = 0; tries < 200; tries++) {
    const style = rand();
    let name;
    if (style < 0.55) name = pick(ADJ) + pick(NOUN) + pick(SUFFIX);
    else if (style < 0.8) name = pick(NOUN) + pick(SUFFIX);
    else name = pick(ADJ) + "_" + pick(NOUN) + pick(SUFFIX);
    if (name.length < 3 || name.length > 20) continue;
    const lower = name.toLowerCase();
    if (!used.has(lower)) {
      used.add(lower);
      return name;
    }
  }
  return null;
}

// A rating with matching Glicko rd / record for a given game count.
function ratingBlock(baseRating) {
  const games = between(15, 600);
  // More games -> tighter rd (settled rating).
  const rd = Math.round(Math.max(35, Math.min(140, 30 + 5200 / games)));
  const rating = Math.max(700, Math.min(2450, Math.round(baseRating + (rand() - 0.5) * 120)));
  // Win rate skews slightly with rating but stays believable.
  const winP = 0.35 + Math.min(0.25, Math.max(-0.15, (rating - 1500) / 4000)) + (rand() - 0.5) * 0.1;
  const drawP = 0.08 + rand() * 0.12;
  const wins = Math.round(games * Math.max(0.1, Math.min(0.8, winP)));
  const draws = Math.round(games * drawP);
  const losses = Math.max(0, games - wins - draws);
  const peak = Math.round(rating + between(0, 120));
  return { rating, rd, games, wins, losses, draws, peak };
}

const CREATED_BASE = 1748736000000; // 2025-06-01, well in the past
const N = 150;
const used = new Set();
const lines = [];
lines.push("-- Seed ~150 fake players onto the Nerf and Buff leaderboards.");
lines.push("-- Generated by scripts/gen-seed-leaderboard.cjs (deterministic).");
lines.push("-- Fake users have id LIKE 'seed_%' and password_hash 'unusable' so they");
lines.push("-- can never log in and are removable via scripts/revert-seed-leaderboard.sql.");
lines.push("");

let both = 0, nerfOnly = 0, buffOnly = 0, ratingRows = 0;
for (let i = 0; i < N; i++) {
  const name = makeName(used);
  if (!name) continue;
  const lower = name.toLowerCase();
  const id = "seed_" + lower;
  const created = CREATED_BASE + i * 3600000 + between(0, 3600000);
  // Base skill for this player, spread across the ladder.
  const base = 850 + Math.round((i / N) * 1450) + (rand() - 0.5) * 200;
  lines.push(
    `INSERT OR IGNORE INTO users (id, username, username_lower, password_hash, created_at) VALUES ` +
      `('${id}', '${name}', '${lower}', 'unusable', ${created});`,
  );
  // Category coverage: most players on both boards.
  const roll = rand();
  const cats = roll < 0.7 ? ["nerf", "buff"] : roll < 0.85 ? ["nerf"] : ["buff"];
  if (cats.length === 2) both++; else if (cats[0] === "nerf") nerfOnly++; else buffOnly++;
  for (const cat of cats) {
    const b = ratingBlock(base);
    ratingRows++;
    lines.push(
      `INSERT OR IGNORE INTO user_ratings (user_id, category, rating, rd, games, wins, losses, draws, peak) VALUES ` +
        `('${id}', '${cat}', ${b.rating}, ${b.rd}, ${b.games}, ${b.wins}, ${b.losses}, ${b.draws}, ${b.peak});`,
    );
  }
}
lines.push("");
lines.push(`-- players: ${used.size}, rating rows: ${ratingRows} (both=${both}, nerfOnly=${nerfOnly}, buffOnly=${buffOnly})`);
process.stdout.write(lines.join("\n") + "\n");
