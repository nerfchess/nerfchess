// Game-snapshot round-trip harness. Run after `npm run server:build`.
//
//   npm run test:snapshot
//
// Guards the checkpoint feature the worker uses to avoid replaying a house
// game from ply 0 on every bot move. Two properties are asserted, because the
// worker has no test of its own and a snapshot bug would desync a rated game:
//
//   1. Round-trip fidelity: serializeGame -> deserializeGame reproduces the
//      SAME game (board, captured pools, buff/draft state, RNG state, nerf
//      identity, and the desync fingerprint) at every ply of several games,
//      including ones mutated by board-changing cards.
//   2. Resume equivalence: a snapshot taken at ply K, then advanced by replaying
//      only moves/actions K..N, lands on EXACTLY the state a full replay from
//      ply 0 produces. This is the invariant the checkpoint relies on.
//
// If either breaks, the worker's fallback (full replay on a version/fingerprint
// mismatch) still keeps prod correct — but this harness is meant to catch it
// long before that.

const path = require("path");
function load(mod) {
  return require(path.join(__dirname, "..", "dist-server", "src", "engine", mod));
}

const {
  UNRESTRICTED_NERF,
  acquireBuff,
  activateBuff,
  enableDraftMode,
  legalMoves,
  newGame,
  playMove,
  serializeGame,
  deserializeGame,
  GAME_SNAPSHOT_VERSION,
} = load("game.js");
const { moveFromUCI, moveToUCI } = load("board.js");
const { desyncFingerprint, compareFingerprints } = load("desync.js");
const { PLAYABLE_NERFS } = load("nerfs/library.js");

const errors = [];
function check(cond, msg) {
  if (!cond) errors.push(msg);
}

const sq = (name) => (name.charCodeAt(1) - 49) * 8 + (name.charCodeAt(0) - 97);

// The buff state minus the fields serializeGame intentionally drops (transient,
// regenerated by the next apply cycle), so a live game and a round-tripped one
// compare equal.
function stableBuffs(buffs) {
  if (!buffs) return null;
  const { mutations, lastHookMutations, clockFx, ...rest } = buffs;
  void mutations;
  void lastHookMutations;
  void clockFx;
  return rest;
}

// Deep structural + fingerprint equality of two live games.
function assertGameEqual(a, b, label) {
  check(JSON.stringify(a.board) === JSON.stringify(b.board), `${label}: board diverged`);
  check(
    JSON.stringify(a.captured) === JSON.stringify(b.captured),
    `${label}: captured pools diverged`,
  );
  check(
    JSON.stringify(stableBuffs(a.buffs)) === JSON.stringify(stableBuffs(b.buffs)),
    `${label}: buff/draft state diverged`,
  );
  check(a.white.nerf.id === b.white.nerf.id, `${label}: white nerf id diverged`);
  check(a.black.nerf.id === b.black.nerf.id, `${label}: black nerf id diverged`);
  check(a.white.rng.getState() === b.white.rng.getState(), `${label}: white RNG state diverged`);
  check(a.black.rng.getState() === b.black.rng.getState(), `${label}: black RNG state diverged`);
  const cmp = compareFingerprints(desyncFingerprint(a), desyncFingerprint(b));
  check(cmp.ok, `${label}: desync fingerprints diverged (${JSON.stringify(cmp.diverged)})`);
}

function runOp(g, op) {
  if (op.t === "move") {
    const m = legalMoves(g).find((x) => moveToUCI(x) === op.u) || moveFromUCI(g.board, op.u);
    if (!m) throw new Error(`op move not playable: ${op.u}`);
    playMove(g, m);
  } else if (op.t === "pick") {
    acquireBuff(g, op.c, op.id, op.tier);
  } else if (op.t === "use") {
    check(activateBuff(g, op.c, op.idx, op.picks), `use ${op.c}#${op.idx} activation failed`);
  } else {
    throw new Error(`unknown op ${op.t}`);
  }
}

// Run a scripted game and assert (1) a snapshot round-trips at every ply and
// (2) a snapshot taken at `resumeAt` replays forward to the same final state.
function scenario(label, seed, mode, ops, resumeAt) {
  const g = newGame(UNRESTRICTED_NERF, UNRESTRICTED_NERF, seed);
  enableDraftMode(g, seed, { mode });

  let resumeSnap = null;
  for (let i = 0; i < ops.length; i++) {
    if (i === resumeAt) resumeSnap = serializeGame(g);
    const rt = deserializeGame(serializeGame(g));
    check(rt !== null, `${label} ply ${i}: deserialize returned null`);
    if (rt) assertGameEqual(g, rt, `${label} ply ${i} round-trip`);
    runOp(g, ops[i]);
  }
  const rtFinal = deserializeGame(serializeGame(g));
  if (rtFinal) assertGameEqual(g, rtFinal, `${label} final round-trip`);

  // Resume: rebuild from the ply-K snapshot and replay only K..N.
  const resumed = deserializeGame(resumeSnap);
  check(resumed !== null, `${label}: resume snapshot deserialize returned null`);
  if (resumed) {
    for (let i = resumeAt; i < ops.length; i++) runOp(resumed, ops[i]);
    assertGameEqual(g, resumed, `${label} resume-from-snapshot(ply ${resumeAt})`);
  }
}

// --- Scenario 1: activated board removal (Detonate) -------------------------
scenario(
  "detonate",
  101,
  "buff",
  [
    { t: "pick", c: "w", id: "detonate", tier: 4 },
    { t: "move", u: "e2e4" },
    { t: "move", u: "e7e5" },
    { t: "use", c: "w", idx: 0, picks: [{ square: sq("e4") }] },
    { t: "move", u: "b8c6" },
  ],
  1,
);

// --- Scenario 2: hidden passive that fires on a capture ---------------------
scenario(
  "detonation_field",
  202,
  "buff",
  [
    { t: "pick", c: "w", id: "detonation_field", tier: 6 },
    { t: "move", u: "e2e4" },
    { t: "move", u: "e7e5" },
    { t: "move", u: "d1h5" },
    { t: "move", u: "b8c6" },
    { t: "move", u: "h5f7" }, // Qxf7: the capture detonates around f7
  ],
  2, // snapshot BEFORE the hook-firing capture, then replay through it
);

// --- Scenario 3: summon + capture + revive (captured-pool coherence) --------
scenario(
  "summon+revive",
  303,
  "buff",
  [
    { t: "pick", c: "w", id: "summon_knight", tier: 3 },
    { t: "use", c: "w", idx: 0, picks: [{ square: sq("d4") }] },
    { t: "move", u: "e7e5" },
    { t: "move", u: "a2a3" },
    { t: "move", u: "e5d4" }, // black captures the summoned knight
    { t: "pick", c: "w", id: "resurrect", tier: 4 },
    { t: "use", c: "w", idx: 1, picks: [{ square: sq("c3") }] },
  ],
  2,
);

// --- Scenario 4: nerf-mode game with real nerfs (slot RNG + nerf state) -----
// Real nerfs run init (seeds slot state/RNG) and hooks (may consume slot RNG),
// so this exercises the parts UNRESTRICTED_NERF does not. The move script is
// generated by walking first-legal moves so it is always playable under the
// nerfs' restrictions.
{
  const [nerfA, nerfB] = PLAYABLE_NERFS.filter((n) => n.implemented).slice(0, 2);
  check(!!nerfA && !!nerfB, "nerf-mode: need two implemented nerfs for the test");
  if (nerfA && nerfB) {
    const seed = 4040;
    // Generate a playable move script off a throwaway game.
    const gen = newGame(nerfA, nerfB, seed);
    enableDraftMode(gen, seed, { mode: "nerf" });
    const ops = [];
    for (let i = 0; i < 10; i++) {
      const lm = legalMoves(gen);
      if (!lm.length || gen.result) break;
      const u = moveToUCI(lm[0]);
      ops.push({ t: "move", u });
      playMove(
        gen,
        legalMoves(gen).find((m) => moveToUCI(m) === u),
      );
    }
    check(ops.length >= 4, "nerf-mode: generated too few moves to test a resume");

    // Now run the real scenario with those moves, but with real nerfs. Inline
    // (scenario() hardcodes UNRESTRICTED_NERF) so the slots carry real nerfs.
    const g = newGame(nerfA, nerfB, seed);
    enableDraftMode(g, seed, { mode: "nerf" });
    const resumeAt = 2;
    let resumeSnap = null;
    for (let i = 0; i < ops.length; i++) {
      if (i === resumeAt) resumeSnap = serializeGame(g);
      const rt = deserializeGame(serializeGame(g));
      if (rt) assertGameEqual(g, rt, `nerf-mode ply ${i} round-trip`);
      runOp(g, ops[i]);
    }
    const resumed = deserializeGame(resumeSnap);
    if (resumed) {
      for (let i = resumeAt; i < ops.length; i++) runOp(resumed, ops[i]);
      assertGameEqual(g, resumed, `nerf-mode resume-from-snapshot(ply ${resumeAt})`);
    }
    // The rehydrated slots must carry the real nerf identities, not a fallback.
    if (resumed) {
      check(resumed.white.nerf.id === nerfA.id, "nerf-mode: white nerf id lost on round-trip");
      check(resumed.black.nerf.id === nerfB.id, "nerf-mode: black nerf id lost on round-trip");
    }
  }
}

// --- Version guard: a snapshot from another schema must be rejected ----------
{
  const g = newGame(UNRESTRICTED_NERF, UNRESTRICTED_NERF, 55);
  enableDraftMode(g, 55, { mode: "buff" });
  const snap = serializeGame(g);
  check(snap.v === GAME_SNAPSHOT_VERSION, "version guard: snapshot missing its version stamp");
  const stale = { ...snap, v: GAME_SNAPSHOT_VERSION + 1 };
  check(
    deserializeGame(stale) === null,
    "version guard: a stale-version snapshot must deserialize to null (forces full replay)",
  );
}

if (errors.length) {
  console.error("snapshot harness FAILED:");
  for (const e of errors) console.error("  - " + e);
  process.exit(1);
}
console.log(
  `OK: snapshot harness passed (round-trip + resume equivalence across ` +
    `4 scenarios: detonate, detonation_field, summon+revive, nerf-mode; plus the version guard)`,
);
