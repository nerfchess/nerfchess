// Build-time generator for src/lib/cardGlyphMap.gen.ts: which effect-category
// glyph each card wears (src/components/icons/cardGlyphs.tsx), and which cards
// keep a hand-picked lucide face instead (the CARD_ICON_OVERRIDES table in
// scripts/gen-card-icons.mjs, tier 7+ name-matched picks).
//
//   node scripts/gen-card-glyphs.mjs           # regenerate
//   node scripts/gen-card-glyphs.mjs --check   # CI: fail if stale
//
// Inputs are docs/card-registry.json (effectCategory per card, kept current by
// npm run test:card-registry) and the overrides table read as source text, so
// this never imports the engine and runs in a second.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src", "lib", "cardGlyphMap.gen.ts");
const CHECK = process.argv.includes("--check");

const registry = JSON.parse(fs.readFileSync(path.join(ROOT, "docs", "card-registry.json"), "utf8")).cards;
const iconsSrc = fs.readFileSync(path.join(ROOT, "scripts", "gen-card-icons.mjs"), "utf8");
const start = iconsSrc.indexOf("const CARD_ICON_OVERRIDES = {");
const end = iconsSrc.indexOf("\n};", start);
const overrides = iconsSrc.slice(start, end);
const curated = [...overrides.matchAll(/^\s{2}([a-z0-9_]+):\s*"[A-Za-z0-9]+"/gm)].map((m) => m[1]).sort();

const categories = [...new Set(registry.map((c) => c.effectCategory))].sort();
const catIndex = new Map(categories.map((c, i) => [c, i]));
// A few ids exist as both a nerf and a buff; the first row (registry order)
// wins, since the face lookup is keyed by id alone.
const seen = new Set();
const rows = registry
  .filter((c) => c.implemented && !seen.has(c.id) && seen.add(c.id))
  .map((c) => [c.id, catIndex.get(c.effectCategory)])
  .sort((a, b) => (a[0] < b[0] ? -1 : 1));

const lines = [
  "// GENERATED by scripts/gen-card-glyphs.mjs. Do not edit; run: node scripts/gen-card-glyphs.mjs",
  "//",
  "// Card id -> effect-category index (GLYPH_CATEGORIES), and the ids that keep",
  "// a curated lucide face instead of the category glyph.",
  "",
  `export const GLYPH_CATEGORIES = ${JSON.stringify(categories)} as const;`,
  "",
  "export const CARD_GLYPH_CATEGORY: Record<string, number> = {",
  ...rows.map(([id, i]) => `  ${JSON.stringify(id)}: ${i},`),
  "};",
  "",
  `export const CURATED_ICON_IDS = new Set<string>(${JSON.stringify(curated)});`,
  "",
];
const next = lines.join("\n");
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (CHECK) {
  if (prev !== next) {
    console.error("[gen-card-glyphs] STALE: src/lib/cardGlyphMap.gen.ts differs. Run: node scripts/gen-card-glyphs.mjs");
    process.exit(1);
  }
  console.log(`[gen-card-glyphs] check OK: ${rows.length} cards, ${categories.length} categories, ${curated.length} curated`);
} else {
  fs.writeFileSync(OUT, next);
  console.log(`[gen-card-glyphs] wrote ${OUT}: ${rows.length} cards, ${categories.length} categories, ${curated.length} curated`);
}
